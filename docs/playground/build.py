"""Build the playground page (index.html) from template.html, pemu.js,
play.js and data.js, and write data.js from the real firmware and tables.

    python3 docs/playground/build.py [--fragment PATH]

--fragment also writes the page without <!doctype>/<html>/<head>/<body>
(for hosts that add their own). sw/tests/test_playground.py checks that
both generated files are up to date.
"""

import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "sw"))

from pemu import music, vga  # noqa: E402


def data_js():
    programs = {}
    for path in sorted(glob.glob(os.path.join(HERE, "..", "..", "sw", "programs", "*.pasm"))):
        programs[os.path.basename(path)[:-5]] = open(path).read()
    words = music.song_words(music.ODE_TO_JOY)
    data = {
        "programs": programs,
        "font": vga.FONT,
        "music": {"ode": words, "steps": sum(s for _, s in music.ODE_TO_JOY),
                  "step": music.step_crc(0.25), "gap": music.tone_config().crc_init},
    }
    return ("// Generated by build.py from sw/programs and sw/pemu: do not edit.\n"
            "(function (root) {\n  const DATA = " + json.dumps(data, indent=None) + ";\n"
            "  if (typeof module !== \"undefined\" && module.exports) module.exports = DATA;\n"
            "  else root.PEMU_DATA = DATA;\n"
            "})(typeof window !== \"undefined\" ? window : globalThis);\n")


def page(data):
    tpl = open(os.path.join(HERE, "template.html")).read()
    scripts = "".join(f"<script>\n{src}</script>\n" for src in (
        open(os.path.join(HERE, "pemu.js")).read(), data,
        open(os.path.join(HERE, "play.js")).read()))
    return tpl.replace("<!-- SCRIPTS -->\n", scripts)


def full(fragment):
    return ("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1, viewport-fit=cover\">\n"
            + fragment.replace("</style>", "</style>\n</head>\n<body>", 1)
            + "</body>\n</html>\n")


def build():
    data = data_js()
    frag = page(data)
    return data, frag, full(frag)


def main(argv):
    data, frag, html = build()
    open(os.path.join(HERE, "data.js"), "w").write(data)
    open(os.path.join(HERE, "index.html"), "w").write(html)
    if "--fragment" in argv:
        open(argv[argv.index("--fragment") + 1], "w").write(frag)
    print(f"index.html: {len(html) // 1024} KB")


if __name__ == "__main__":
    main(sys.argv[1:])
